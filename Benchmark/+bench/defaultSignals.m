function classes = defaultSignals(net)
% DEFAULTSIGNALS  Default sleep graphoelement classes injected by bidsfun_gedai_benchmark.
%
%   classes = bench.defaultSignals()
%   classes = bench.defaultSignals('EGI128')
%
%   Returns a struct array, one element per event class. Every numeric parameter can be a
%   fixed value or a [min max] range that is sampled uniformly per event. Edit the returned
%   struct (or build your own with the same fields) and pass it as 'signals'.
%
%   Fields
%   ------
%   name          class label, written as trial_type in the events table
%   kind          'spindle' (Hann-envelope sinusoid) or 'slowwave' (area-matched biphasic
%                 Gaussian pair: negative lobe, then a broader positive lobe)
%   stages        stage digits the class is injected into (N3 -3, N2 -2, REM 0, Wake 1)
%   density       events per minute, one value per entry of stages (Poisson per epoch)
%   amplitude     uV at the peak channel of the average-referenced field: envelope peak for
%                 spindles, peak-to-peak for slow waves
%   duration      s, spindles only (slow-wave length follows from the lobe widths)
%   freq          Hz, spindle centre frequency
%   chirp         Hz, frequency change from event start to end (negative = decelerating)
%   negwidth      s, Gaussian SD of the negative lobe (slow waves)
%   poswidth      s, Gaussian SD of the positive lobe (slow waves)
%   gap           s, time from negative to positive peak (slow waves)
%   anchors       channel labels; each event picks one and is generated by the cortical
%                 patch under that channel (see bench.anchorSource)
%   patchradius   m, radius of the cortical source patch (Gaussian weights, SD = radius/2)
%   speed         m/s, travelling-wave speed along the anterior-posterior axis; 0 = the
%                 patch fires synchronously
%   coupleclass   name of a class to nest into this event ('' = none), e.g. a spindle on
%                 the up-state of a K-complex
%   coupleprob    probability that an event carries a nested coupleclass event
%   couplelag     s, onset of the nested event relative to this event's negative peak
%   detectband    Hz, band used by the class's detector and amplitude measure
%
%   Defaults, and where they come from
%   ----------------------------------
%   Densities and morphology are typical adult values, meant as plausible starting points,
%   not fits to DROP: fast spindles 12.5-15 Hz centro-parietal and slow spindles 10-12 Hz
%   frontal (e.g. Mölle et al. 2011, Sleep 34:1411); K-complex N550/P900 morphology
%   (Colrain 2005, Sleep 28:255); slow oscillations frontal-dominant, travelling front to
%   back at about 1.2-7 m/s (Massimini et al. 2004, J Neurosci 24:6862). Amplitudes are for
%   average-referenced 256-channel data, which reads lower than mastoid-referenced values.

arguments
    net {mustBeMember(net, {'EGI256', 'EGI128'})} = 'EGI256'
end

N3 = -3; N2 = -2;
[~, map] = chans1020(struct('chanlocs', struct('labels', repmat({''}, 1, 300))), false, 'net', net);
label = @(name) sprintf('E%d', map.(name));
frontal  = {label('Fz'), label('F3'), label('F4')};
central  = {label('C3'), label('C4')};
parietal = {label('Pz'), label('P3'), label('P4')};

fastSpindle             = newClass('spindle_fast', 'spindle');
fastSpindle.stages      = [N2 N3];
fastSpindle.density     = [3 1.5];
fastSpindle.amplitude   = [10 30];
fastSpindle.duration    = [0.5 2];
fastSpindle.freq        = [12.5 15];
fastSpindle.chirp       = [-1 0];
fastSpindle.anchors     = [central parietal];
fastSpindle.patchradius = 0.02;
fastSpindle.detectband  = [11 16];

slowSpindle             = newClass('spindle_slow', 'spindle');
slowSpindle.stages      = [N2 N3];
slowSpindle.density     = [1.5 1];
slowSpindle.amplitude   = [10 25];
slowSpindle.duration    = [0.5 2];
slowSpindle.freq        = [10 12];
slowSpindle.chirp       = [-0.5 0];
slowSpindle.anchors     = frontal;
slowSpindle.patchradius = 0.02;
slowSpindle.detectband  = [9 12.5];

kComplex             = newClass('kcomplex', 'slowwave');
kComplex.stages      = N2;
kComplex.density     = 1.5;
kComplex.amplitude   = [80 180];
kComplex.negwidth    = [0.08 0.13];
kComplex.poswidth    = [0.18 0.30];
kComplex.gap         = [0.35 0.50];
kComplex.anchors     = frontal;
kComplex.patchradius = 0.035;
kComplex.speed       = [1 5];
kComplex.coupleclass = 'spindle_fast';
kComplex.coupleprob  = 0.5;
kComplex.couplelag   = [0.3 0.6];
kComplex.detectband  = [0.5 4];

slowOsc             = newClass('slowosc', 'slowwave');
slowOsc.stages      = [N2 N3];
slowOsc.density     = [3 12];
slowOsc.amplitude   = [60 140];
slowOsc.negwidth    = [0.12 0.22];
slowOsc.poswidth    = [0.20 0.35];
slowOsc.gap         = [0.45 0.75];
slowOsc.anchors     = [frontal central];
slowOsc.patchradius = 0.05;
slowOsc.speed       = [1.2 7];
slowOsc.coupleclass = 'spindle_fast';
slowOsc.coupleprob  = 0.2;
slowOsc.couplelag   = [0.3 0.6];
slowOsc.detectband  = [0.5 4];

classes = [fastSpindle, slowSpindle, kComplex, slowOsc];
end

% -------------------------------------------------------------------------
function c = newClass(name, kind)
c = struct('name', name, 'kind', kind, 'stages', [], 'density', 0, 'amplitude', 0, ...
    'duration', 1, 'freq', NaN, 'chirp', 0, 'negwidth', NaN, 'poswidth', NaN, 'gap', NaN, ...
    'anchors', {{}}, 'patchradius', 0.02, 'speed', 0, 'coupleclass', '', 'coupleprob', 0, ...
    'couplelag', 0, 'detectband', [0.5 4]);
end
