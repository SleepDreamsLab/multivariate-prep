%%% Start clean
clearvars
clc; close all

%%% Dependancies
run('dependancies.m')

%%% Projects to run
[BIDS_DROP] = smartcache( ...
    @() bidswizard({'data-drop'}, '\\vs03.herseninstituut.knaw.nl\VS03-SandC-1\data\nin', 'rawdata'), ...
    fullfile(pwd, 'BidsFiles', 'BIDS_DROP.mat'), false, {'BIDS_DROP'});
BIDS = BIDS_DROP{1}; fails = [];

% Variables
acqlabel = '';
refresh = false;
targetsrate = 250;
removeDC = false;
derivfolder = 'prep-ged-ica';
scoringpath = fullfile(BIDS.pth, '..\derivatives\scores\final');
leadfieldpath = '\\vs03.herseninstituut.knaw.nl\VS03-SandD-4\PM\Data_Analysis\Brainstorm_db\DROP_Leadfields2\data';
BIDS.description = []; BIDS.description.Name = 'DROP';

% Descs. badchandesc is deliberately independent of filtdesc: bad channel detection is
% decided once per recording, so changing the filter settings below no longer forces a
% re-detection, and re-detecting does not invalidate the filtered files.
badchandesc = 'hp';
filtdesc    = 'hpzc';
geddesc     = 'hpzcged';
subjects    = {'sub-drop0001'};
sessions    = {'ses-t1', 'ses-t2', 'ses-t3', 'ses-t4', 'ses-t5'};

% %%% Build leadfield matrices
% build_leadfield_bids(BIDS, 'ProtocolName', 'DROP_Leadfields2', 'ForceReprocess', refresh, ...
%     'QCDir', fullfile(BIDS.pth, 'derivatives\leadfields\figures\electrode-headmodel-fit'))

for ises = 1:numel(sessions)
    session = sessions(ises);

    % *** Detect flat and bad channels (before any line-noise removal)
    %     targetsrate and removeDC must match the prepare stage below, or detection and
    %     filtering see different data.
    fails.badchan = bidsfun_detect_badchans(BIDS, ...
        'subjectfilter', subjects, ...
        'sessionfilter', session, ...
        'acqlabel', acqlabel, ...
        'refresh', refresh, ...
        'derivfolder', derivfolder, ...
        'targetsrate', targetsrate, ...
        'removeDC', removeDC, ...
        'desc', badchandesc);

    % *** HP filter, remove bad channels, zapline, cleanline
    fails.prep = bidsfun_hp_zap_cleanline(BIDS, ...
        'subjectfilter', subjects, ...
        'sessionfilter', session, ...
        'acqlabel', acqlabel, ...
        'refresh', refresh, ...
        'derivfolder', derivfolder, ...
        'targetsrate', targetsrate, ...
        'removeDC', removeDC, ...
        'zapline', 1, ...
        'cleanline', 1, ...
        'zapline2', 0, ...
        'badchandesc', badchandesc, ...
        'desc', filtdesc);

    % *** Evaluate filter success
    fails.eval = bidsfun_evalfigs(BIDS, ...
        'subjectfilter', subjects, ...
        'sessionfilter', session, ...
        'acqlabel', acqlabel, ...
        'refresh', refresh, ...
        'derivfolder', derivfolder, ...
        'scoringpath', scoringpath, ...
        'filtdesc', filtdesc);

    % *** GEDAI
    r = gedai.defaultRuns();
    fails.gedai = bidsfun_run_gedai(BIDS, ...
        'RunMode', 'StageSpecific', ...
        'runs', r, ...
        'acqlabel', acqlabel, ...
        'refresh', refresh, ...
        'subjectfilter', subjects, ...
        'sessionfilter', session, ...
        'geddesc', geddesc, ...
        'inputdesc', filtdesc, ...
        'badchandesc', badchandesc, ...
        'leadfielddir', leadfieldpath, ...
        'scoringpath', scoringpath, ...
        'derivfolder', derivfolder ...        
        );
end

