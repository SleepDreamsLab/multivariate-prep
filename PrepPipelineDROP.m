%%% Start clean
clearvars
clc; close all

%%% Dependancies
run('dependancies.m')

%%% Build BIDS structure from data folder
%%% BIDS structure contains all pathing and subject information
[BIDS_DROP] = smartcache( ...
    @() bidswizard({'data-drop'}, '\\vs03.herseninstituut.knaw.nl\VS03-SandC-1\data\nin', 'rawdata'), ...
    fullfile(pwd, 'BidsFiles', 'BIDS_DROP.mat'), false, {'BIDS_DROP'}); 
BIDS = BIDS_DROP{1}; fails = [];

% Variables
acqlabel        = '';    % acqlabel of EEG file, leave '' if not used
refresh         = false; % re-run when outputs already exist
refreshFigures  = false; % re-run when figures alreaady exist
targetsrate     = 250;   % down-sample to this srate
removeDC        = false; % apply 0.1 Hz high-pass filter?
derivfolder     = 'prep-zc-ged'; % name of output folder within derivatives folder
scoringpath     = fullfile(BIDS.pth, '..\derivatives\scores\final'); % where to find scoring files
leadfieldpath   = '\\vs03.herseninstituut.knaw.nl\VS03-SandD-4\PM\Data_Analysis\Brainstorm_db\DROP_Leadfields2\data'; % where to find leadfield matrices
BIDS.description = []; BIDS.description.Name = 'DROP'; % some actions are project specific (e.g., chanlocs import)

% "desc" labels 
% output filenames receive a "desc" label, indicating what was done to them
badchandesc = 'hp';      % hp:  high-pass filtered
filtdesc    = 'hpzc';    % zc:  zapline-plus & cleanline
geddesc     = 'hpzcged'; % ged: gedai 

% Subejct and Session filter
subjects    = {'sub-drop0001', 'sub-drop0002', 'sub-drop0003'};   % {'sub-drop0001', '...'} or {} to run on all subjects
sessions    = {'ses-t1', 'ses-t2', 'ses-t3', 'ses-t4', 'ses-t5'}; % {'ses-t1', '...'} or {} to run on all sessions



%%% --- PIPELINE START --- %%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% Universal default parameters
defauls = [];
defauls.subjectfilter  = subjects;
defauls.sessionfilter  = sessions;
defauls.derivfolder    = derivfolder;
defauls.acqlabel       = acqlabel;
defauls.refresh        = refresh;
defauls = namedargs2cell(defauls);

% %%% Step #0 -> Build leadfield matrices
% build_leadfield_bids(BIDS, 'ProtocolName', 'DROP_Leadfields2', 'ForceReprocess', refresh, ...
%     'QCDir', fullfile(BIDS.pth, 'derivatives\leadfields\figures\electrode-headmodel-fit'))

%%% Step #1 -> Detect flat and bad channels
fails.badchan = bidsfun_detect_badchans(BIDS, defauls{:}, ...
    'badchannumsamples', 25, ...
    'badchanstride', 2, ...
    'badchanmaxbrokentime', .3, ...    
    'flatmaxbrokentime', .3, ...
    'targetsrate', targetsrate, ...
    'removeDC', removeDC, ...
    'desc', badchandesc);

%%% Step #2 -> HP filter, remove bad channels, zapline, cleanline
fails.prep = bidsfun_hp_zap_cleanline(BIDS, defauls{:}, ...
    'noisefreqs', 50, ...
    'chunkLength', 300, ...
    'noiseCompDetectSigma', 5, ...
    'adaptiveSigma', false, ...
    'cleanlineWinstep', 2, ...
    'cleanlinePad', 2, ...
    'targetsrate', targetsrate, ...
    'removeDC', removeDC, ...
    'badchandesc', badchandesc, ...
    'desc', filtdesc);

%%% Step #2.1 -> Evaluate success of step #1 and #2 
fails.eval = bidsfun_evalfigs(BIDS, defauls{:}, ...
    'refresh', refreshFigures, ...
    'scoringpath', scoringpath, ...
    'afterdesc', filtdesc);

%%% Step #3 -> AVG reference, run GEDAI
r = gedai.defaultRuns();
fails.gedai = bidsfun_gedai(BIDS, defauls{:}, ...
    'runs', r, ...
    'RunMode', 'StageSpecific', ...
    'geddesc', geddesc, ...
    'inputdesc', filtdesc, ...
    'leadfielddir', leadfieldpath, ...
    'scoringpath', scoringpath, ...
    'evalplots', false ...
    );

%%% Step #3.1 -> Evaluate success of step #3
fails.eval = bidsfun_evalfigs(BIDS, defauls{:}, ...
    'PlotEpochOverlay', true, ...
    'PlotExponentByStage', true, ...
    'PlotSlopesTimecourse', true, ...
    'avgrefbefore', true, ...
    'avgrefafter', false, ...
    'refresh', refreshFigures, ...
    'scoringpath', scoringpath, ...
    'afterdesc', geddesc);    



